#!/usr/bin/env python3
"""Build the bloom palettes in app/assets/css/palettes.css from a few pinned OKLCH anchors.

    python3 scripts/ramps.py            print palettes.css
    python3 scripts/ramps.py --write    rewrite palettes.css
    python3 scripts/ramps.py --check    fail if palettes.css values differ (formatting is ignored)
    python3 scripts/ramps.py --contrast report semantic colours against each theme's background
"""

import math
import re
import sys
from pathlib import Path

CSS_PATH = Path(__file__).resolve().parent.parent / "app" / "assets" / "css" / "palettes.css"
STOPS = [50, 100, 200, 300, 400, 500, 600, 700, 800, 900, 950]

# Theme backgrounds, matching --ui-bg in main.css.
PAPER = (98.5, 0.010, 350)
NIGHT = (21.0, 0.035, 345)

# Pinned stops as (lightness %, chroma, hue). Everything else is interpolated in OKLab.
RAMPS = {
    "peony": ("Peony: pink primary", {
        50: (97.5, 0.012, 358), 300: (80, 0.120, 355), 600: (55, 0.190, 358), 700: (47, 0.170, 358), 950: (22, 0.080, 358)}),
    "lilac": ("Lilac: secondary", {
        50: (97.5, 0.012, 315), 300: (80, 0.090, 315), 600: (52, 0.140, 315), 700: (45, 0.130, 315), 950: (21, 0.060, 315)}),
    "hellebore": ("Hellebore: success", {
        50: (97.5, 0.015, 150), 300: (82, 0.120, 150), 600: (56, 0.130, 150), 700: (48, 0.110, 150), 950: (23, 0.050, 150)}),
    "cornflower": ("Cornflower: info", {
        50: (97.5, 0.012, 255), 300: (80, 0.090, 255), 600: (52, 0.150, 255), 700: (45, 0.140, 255), 950: (22, 0.060, 255)}),
    "marigold": ("Marigold: warning", {
        50: (98, 0.025, 85), 300: (85, 0.140, 80), 600: (62, 0.150, 65), 700: (52, 0.130, 60), 950: (25, 0.060, 55)}),
    "poppy": ("Poppy: error", {
        50: (97.5, 0.012, 25), 300: (78, 0.130, 25), 600: (53, 0.200, 25), 700: (46, 0.180, 25), 950: (22, 0.080, 25)}),
    "plum": ("Plum: pink-tinted neutral for text, borders and surfaces", {
        50: (97.5, 0.010, 350), 200: (90, 0.030, 350), 300: (78, 0.030, 350), 600: (52, 0.055, 345),
        700: (45, 0.050, 345), 800: (36, 0.050, 345), 900: (28, 0.060, 345), 950: (20, 0.045, 345)}),
}

# Steps each theme uses for the semantic colours (see :root and .dark in main.css).
SEMANTIC = {
    "primary": ("peony", 600, 300), "secondary": ("lilac", 600, 300), "success": ("hellebore", 700, 300),
    "info": ("cornflower", 700, 300), "warning": ("marigold", 700, 300), "error": ("poppy", 600, 300),
}


# OKLCH <-> OKLab <-> sRGB

def lch_to_lab(lch):
    l, c, h = lch
    rad = math.radians(h)
    return (l / 100, c * math.cos(rad), c * math.sin(rad))


def lab_to_lch(lab):
    l, a, b = lab
    return (l * 100, math.hypot(a, b), math.degrees(math.atan2(b, a)) % 360)


def lab_to_linear_rgb(lab):
    l, a, b = lab
    l_, m_, s_ = (l + 0.3963377774 * a + 0.2158037573 * b, l - 0.1055613458 * a - 0.0638541728 * b,
                  l - 0.0894841775 * a - 1.2914855480 * b)
    lo, me, sh = l_ ** 3, m_ ** 3, s_ ** 3
    return (4.0767416621 * lo - 3.3077115913 * me + 0.2309699292 * sh,
            -1.2684380046 * lo + 2.6097574011 * me - 0.3413193965 * sh,
            -0.0041960863 * lo - 0.7034186147 * me + 1.7076147010 * sh)


def luminance(lch):
    r, g, b = (min(1.0, max(0.0, v)) for v in lab_to_linear_rgb(lch_to_lab(lch)))
    return 0.2126 * r + 0.7152 * g + 0.0722 * b


def contrast(a, b):
    hi, lo = sorted((luminance(a), luminance(b)), reverse=True)
    return (hi + 0.05) / (lo + 0.05)


def build_ramp(anchors):
    """Fill unpinned stops by walking OKLab between neighbouring anchors, by position in STOPS."""
    pinned = sorted(anchors)
    ramp = {}
    for stop in STOPS:
        if stop in anchors:
            ramp[stop] = anchors[stop]
            continue
        lower = max(s for s in pinned if s < stop)
        upper = min(s for s in pinned if s > stop)
        t = (STOPS.index(stop) - STOPS.index(lower)) / (STOPS.index(upper) - STOPS.index(lower))
        a, b = lch_to_lab(anchors[lower]), lch_to_lab(anchors[upper])
        ramp[stop] = lab_to_lch(tuple(a[i] + (b[i] - a[i]) * t for i in range(3)))
    return ramp


def fmt(lch):
    l, c, h = lch
    return f"oklch({round(l, 1):g}% {c:.3f} {round(h):d})"


def render():
    lines = ["/* Generated by scripts/ramps.py from pinned anchors. Edit the script, not this file. */", "@theme {"]
    for name, (label, anchors) in RAMPS.items():
        lines.append(f"  /* {label} */")
        for stop, value in build_ramp(anchors).items():
            lines.append(f"  --color-{name}-{stop}: {fmt(value)};")
        lines.append("")
    lines[-1] = "}"
    return "\n".join(lines) + "\n"


def colour_values(css):
    """Map each --color-* property to its numbers, so formatting and comments don't matter."""
    decls = re.findall(r"(--color-[a-z]+-\d+)\s*:\s*([^;]+);", css)
    return {key: tuple(float(n) for n in re.findall(r"-?\d*\.?\d+", value)) for key, value in decls}


def check():
    expected = colour_values(render())
    actual = colour_values(CSS_PATH.read_text(encoding="utf-8"))
    if actual == expected:
        print(f"ramps: palettes.css matches ({len(RAMPS)} ramps, {len(expected)} stops)")
        return 0
    print("ramps: palettes.css has different values. Run python3 scripts/ramps.py --write.", file=sys.stderr)
    for key in sorted(expected.keys() | actual.keys()):
        if actual.get(key) != expected.get(key):
            print(f"  {key}: css {actual.get(key, 'missing')}, generator {expected.get(key, 'missing')}", file=sys.stderr)
    return 1


def report_contrast():
    worst = 99.0
    for role, (name, light_step, dark_step) in SEMANTIC.items():
        ramp = build_ramp(RAMPS[name][1])
        light, dark = contrast(ramp[light_step], PAPER), contrast(ramp[dark_step], NIGHT)
        worst = min(worst, light, dark)
        print(f"  {role:9} {name}-{light_step} on paper {light:5.2f}:1  |  {name}-{dark_step} on night {dark:5.2f}:1")
    print(f"\n  worst: {worst:.2f}:1 (text needs 4.5:1)")
    return 0 if worst >= 4.5 else 1


if __name__ == "__main__":
    if "--check" in sys.argv:
        raise SystemExit(check())
    if "--contrast" in sys.argv:
        raise SystemExit(report_contrast())
    if "--write" in sys.argv:
        CSS_PATH.write_text(render(), encoding="utf-8")
        print(f"ramps: wrote {CSS_PATH.name}")
    else:
        print(render(), end="")
